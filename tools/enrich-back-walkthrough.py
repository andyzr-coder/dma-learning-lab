def network(bits,fault=None):
    values=dict(zip(['a','b','c'],bits))
    if fault and fault[0] in values:values[fault[0]]=fault[1]
    values['n']=values['a']&values['b']
    if fault and fault[0]=='n':values['n']=fault[1]
    values['y']=values['n']|values['c']
    if fault and fault[0]=='y':values['y']=fault[1]
    return values
