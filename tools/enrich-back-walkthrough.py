def step(title,do,body,figure=None,prompt=None,answer=None):
    r={'title':title,'do':do,'body':body.strip()}
    if figure:r['figure']=figure
    if prompt:r['check']={'prompt':prompt,'answer':answer}
    return r
def walkthrough(module,title,duration,goal,steps,exitprompt,exitanswer,nexttext):
    p=next((ROOT/'content'/'modules').glob(module+'-*.json'))
    data=json.loads(p.read_text(encoding='utf-8-sig'))
    data['walkthrough']={'title':title,'duration':duration,'goal':goal,'steps':steps,'exit':{'prompt':exitprompt,'answer':exitanswer},'next':nexttext}
    save(p.relative_to(ROOT),data)

